#ifndef RESULT_CODE_H
#define RESULT_CODE_H


#define RESULT_OK 0
#define RESULT_BAD_PARAMETER -1
#define RESULT_INVALID_OPERATION -2
#define RESULT_BASE_MODULE_ERROR -3
#define RESULT_UNKNOWN_ERROR -4
#define RESULT_OUT_OF_MEMORY -5
#define RESULT_OVER_LIMIT -6
#define RESULT_UNSUPPORTED -7
#define RESULT_NO_ENOUGH_BUFFER -8
#define RESULT_TIME_OUT -9
#define RESULT_WAIT_FAILED -10
#define RESULT_NO_MEMORY -11


#define RESULT_CODE_TO_STR(result_code) \
result_code == RESULT_OK ? "RESULT_OK" : \
result_code == RESULT_BAD_PARAMETER ? "RESULT_BAD_PARAMETER" : \
result_code == RESULT_INVALID_OPERATION ? "RESULT_INVALID_OPERATION" : \
result_code == RESULT_BASE_MODULE_ERROR ? "RESULT_BASE_MODULE_ERROR" : \
result_code == RESULT_UNKNOWN_ERROR ? "RESULT_UNKNOWN_ERROR" : \
result_code == RESULT_OUT_OF_MEMORY ? "RESULT_OUT_OF_MEMORY" : \
result_code == RESULT_OVER_LIMIT ? "RESULT_OVER_LIMIT" : \
result_code == RESULT_UNSUPPORTED ? "RESULT_UNSUPPORTED" : \
result_code == RESULT_NO_ENOUGH_BUFFER ? "RESULT_NO_ENOUGH_BUFFER" : \
result_code == RESULT_TIME_OUT ? "RESULT_TIME_OUT" : \
result_code == RESULT_WAIT_FAILED ? "RESULT_WAIT_FAILED" : \
result_code == RESULT_NO_MEMORY ? "RESULT_NO_MEMORY" : \
"UNKNOWN"


#endif // RESULT_CODE_H
